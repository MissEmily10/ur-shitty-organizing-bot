EMINEMOVNA = "eminemovna"
EMINEMOVNA_NAME = "🎤 Эминемовна"
EMINEMOVNA_FILE = Path(__file__).resolve().parent.parent / "styles" / "eminemovna.md"
EMINEMOVNA_SIGN = " (🎭 стиль Эминемовны)"
CUSTOM = "custom"

PACK_PROMPT = """Ты пишешь реплики для Telegram-бота-органайзера заметок. Бот должен говорить в стиле этого персонажа:

{card}

Напиши по {n} коротких реплик (до 100 символов) на русском для каждого случая:
{keys}

Правила: реплики только задают тон и не обещают ничего, чего бот не делает; без пошлости, оскорблений, жестокости,
политики и дискриминации. Если персонаж откровенно сексуальный, оскорбительный или жестокий — ответь {{"refused": true}}.
Ответь только JSON: {{"greeting": ["…", …], "saved": […], …}} с ключами {key_list}."""


def _pick(pack: dict, key: str) -> str:
    options = [o for o in pack.get(key) or [] if isinstance(o, str) and o.strip()]
    return random.choice(options).strip() if options else ""


# ---------- Эминемовна: профиль пишется вместе с владелицей ----------


def eminemovna_profile() -> str | None:
    """Текст профиля, если он заполнен (в шапке файла нет строки «статус: черновик»)."""
    try:
        text = EMINEMOVNA_FILE.read_text(encoding="utf-8")
    except OSError:
        return None
    if "статус: черновик" in text.lower():
        return None
    return text


_packs: dict[str, dict] = {}  # в памяти: ключ хранилища → набор


async def _stored_pack(key: str) -> dict | None:
    if key in _packs:
        return _packs[key]
    raw = await notion.get_value(key)
    if not raw:
        return None
    try:
        _packs[key] = json.loads(raw)
    except json.JSONDecodeError:
        return None
    return _packs[key]


async def generate_pack(card: str, variants: int = 4) -> dict:
    """Набор реплик персонажа: один запрос к ИИ. PermissionError — персонаж не прошёл фильтр."""
    keys = "\n".join(f"- {k}: {v}" for k, v in KEYS.items())
    prompt = PACK_PROMPT.format(card=card[:6000], n=variants, keys=keys, key_list=", ".join(KEYS))
    data = ai._json_object(await ai._complete(prompt, 2500))
    if data.get("refused"):
        raise PermissionError("Такого персонажа бот играть не будет: он работает от имени владелицы.")
    pack = {k: [str(x)[:200] for x in v][:8] for k, v in data.items() if k in KEYS and isinstance(v, list)}
    if len(pack) < len(KEYS) // 2:
        raise RuntimeError("ИИ не написал реплики, попробуйте ещё раз.")
    return pack


async def eminemovna_pack() -> dict:
    profile = eminemovna_profile()
    if not profile:
        return {}
    key = "stylepack:eminemovna:" + hashlib.sha256(profile.encode()).hexdigest()[:10]
    pack = await _stored_pack(key)
    if pack is None:
        # Профиль поменялся — набор пишется заново один раз
        pack = await generate_pack(profile, variants=6)
        await notion.set_value(key, json.dumps(pack, ensure_ascii=False))
        _packs[key] = pack
    return pack


# ---------- свой персонаж ----------


async def persona(uid: int) -> dict | None:
    """{"name", "description", "greeting", "examples", "pack"} или None."""
    raw = await notion.get_value(f"persona:{uid}")
    if not raw:
        return None
    try:
        return json.loads(raw)
    except json.JSONDecodeError:
        return None


async def save_persona(uid: int, data: dict | None) -> None:
    await notion.set_value(f"persona:{uid}", json.dumps(data, ensure_ascii=False) if data else "")


def persona_card(p: dict) -> str:
    return (
        f"Имя: {p['name']}\nХарактер и описание: {p['description']}\nПриветствие: {p['greeting']}\n"
        f"Примеры реплик: {p['examples']}"
    )


# ---------- что говорить ----------


def style_name(style: str, persona_name: str | None = None) -> str:
    if style == EMINEMOVNA:
        return EMINEMOVNA_NAME
    if style == CUSTOM:
        return f"🧩 {persona_name or 'Свой персонаж'}"
    return BUILTIN.get(style, BUILTIN["standard"])["name"]


async def _pack_for(uid: int, settings: dict) -> dict:
    style = settings.get("style") or "standard"
    if style in BUILTIN:
        return BUILTIN[style]["pack"]
    try:
        if style == EMINEMOVNA:
            return await eminemovna_pack()
        if style == CUSTOM:
            return ((await persona(uid)) or {}).get("pack") or {}
    except Exception:
        log.exception("style pack failed")
    return {}


async def line(uid: int, key: str) -> str:
    """Реплика стиля человека для случая key; пустая строка — стиль обычный или реплики нет."""
    from . import scheduler  # здесь, а не наверху: scheduler сам импортирует styles

    settings = await scheduler.get_settings(uid)
    text = _pick(await _pack_for(uid, settings), key)
    if text and settings.get("style") == EMINEMOVNA and uid != c.OWNER_ID:
        text += EMINEMOVNA_SIGN
    return text


async def wrap(uid: int, key: str, text: str, html: bool = False) -> str:
    """Добавляет реплику стиля строкой над текстом бота."""
    phrase = await line(uid, key)
    if not phrase:
        return text
    return f"{escape(phrase) if html else phrase}\n{text}"
